const suitNames: Record<string, [string, string]> = { wands: ['权杖','Wands'], cups: ['圣杯','Cups'], swords: ['宝剑','Swords'], pentacles: ['星币','Pentacles'] }
const ranks = ['王牌','二','三','四','五','六','七','八','九','十','侍从','骑士','王后','国王']
const englishRanks = ['Ace','Two','Three','Four','Five','Six','Seven','Eight','Nine','Ten','Page','Knight','Queen','King']

export const catalog: CardDefinition[] = [
  ...majorRows.split('\n').map((line, i): CardDefinition => {
    const [nameZh, nameEn, upright, reversed, meaning, reversedMeaning] = line.split('|')
    const cardId = `major-${String(i).padStart(2,'0')}`
    return { cardId, nameZh, nameEn, arcana: 'major', suit: null, rank: i, imagePath: `${DECK_BASE}/${cardId}.webp`, upright: upright.split('、'), reversed: reversed.split('、'), meaning, reversedMeaning }
  }),
  ...Object.entries(minorRows).flatMap(([suit, rows]) => rows.split('\n').map((line, i): CardDefinition => {
    const [upright, reversed, meaning, reversedMeaning] = line.split('|')
    const cardId = `${suit}-${String(i+1).padStart(2,'0')}`
    return { cardId, nameZh: suitNames[suit][0]+ranks[i], nameEn: `${englishRanks[i]} of ${suitNames[suit][1]}`, arcana: 'minor', suit, rank: i+1, imagePath: `${DECK_BASE}/${cardId}.webp`, upright: upright.split('、'), reversed: reversed.split('、'), meaning, reversedMeaning }
  })),
]
const byId = new Map(catalog.map(card => [card.cardId, card]))
export function getCard(id: string) {
  const card = byId.get(id)
  if (!card) throw new Error('这张牌的资料暂时无法读取')
  return card
}
